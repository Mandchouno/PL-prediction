CREATE TABLE [pl].[pl_fixtures]
(
	[fixture_id] INT NOT NULL PRIMARY KEY,
	Season VARCHAR (100),
	[season_sk] INT,
	[fixture_date] DATETIME2,
	HomeTeam VARCHAR (100),
	AwayTeam VARCHAR (100),
	FullTimeResults VARCHAR (50),
	HomeGoals INT,
	AwayGoals INT,
	StandingDiff INT,
	HomeWins FLOAT,
	AwayWins FLOAT,
	HomeDraws FLOAT,
	AwayDraws FLOAT,
	AvgHomeGoals FLOAT,
	AvgAwayGoals FLOAT,
	AvgHomeShots FLOAT,
	AvgAwayShots FLOAT,
	AvgHomeShotsOnTarget FLOAT,
	AvgAwayShotsOnTarget FLOAT,
	AvgHomeCorners FLOAT,
	AvgAwayCorners FLOAT,
	AvgHomeGoalsConceded FLOAT,
	AvgAwayGoalsConceded FLOAT,
	AvgHomeShotsConceded FLOAT,
	AvgAwayShotsConceded FLOAT,
	[load_date] DATETIME2
)
